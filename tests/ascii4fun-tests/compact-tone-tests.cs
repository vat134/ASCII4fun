using Ascii4Fun.Compact;
using Ascii4Fun.Images;
using Ascii4Fun.Media;
using ImageMagick;

namespace Ascii4Fun.Tests;

public sealed class CompactToneTests
{
    [Theory]
    [InlineData("atkinson", false)]
    [InlineData("atkinson", true)]
    [InlineData("floyd", false)]
    [InlineData("floyd", true)]
    [InlineData("bayer", false)]
    [InlineData("bayer", true)]
    [InlineData("threshold", false)]
    [InlineData("threshold", true)]
    public void TransparentDotsStayClearBesideOpaqueFeatures(string method, bool invert)
    {
        var source = Grid(16, 16, index => (byte)((index * 67) % 256));
        for (var index = 0; index < 256; index++)
            if (index % 3 == 0 || index / 16 == 8) source.Pixels[index * 4 + 3] = 0;
        foreach (var look in new[] { "photo", "texture", "sketch", "soft", "poster" })
        {
            var canvas = CompactArtPipeline.Convert(source, new CompactArtOptions { Look = look, Dither = method, Invert = invert, Edges = 1 });
            for (var index = 0; index < 256; index++)
            {
                if (source.Pixels[index * 4 + 3] != 0) continue;
                var x = index % 16;
                var y = index / 16;
                var dot = y % 4 == 3 ? 6 + x % 2 : y % 4 + (x % 2) * 3;
                var glyph = canvas.Cells[(y / 4) * canvas.WidthInCells + x / 2].Glyph.Value - 0x2800;
                Assert.True((glyph & (1 << dot)) == 0, $"Transparent sample ({x}, {y}) raised dot {dot}.");
            }
        }
    }

    [Fact]
    public async Task RotatedBinaryPhotoRemainsFiniteAfterGuidedTone()
    {
        using var image = new MagickImage(MagickColors.White, 32, 24);
        using var pixels = image.GetPixels();
        for (var y = 0; y < 24; y++)
            for (var x = 0; x < 16; x++) pixels.SetPixel(x, y, [0, 0, 0]);
        var options = new CompactArtOptions { Destination = "twitch", Columns = 16, CropZoom = 1.5, QuarterTurns = 1 };
        using var input = new MemoryStream(image.ToByteArray(MagickFormat.Png));
        var prepared = await MagickStillImageReader.ReadAsync(input, 4, .5, ConversionLimits.Default, false, false, default, options);
        var values = CompactToneMapper.Apply(prepared.Grid, options);
        Assert.All(values, value => Assert.True(double.IsFinite(value) && value is >= 0 and <= 1, $"Invalid tone {value:R}"));
        _ = CompactArtPipeline.Convert(prepared.Grid, options);
    }

    [Fact]
    public void EveryBraillePatternRetainsItsSpatialBits()
    {
        // Unicode dot numbering: left top three, right top three, then bottom left/right.
        (int X, int Y)[] positions = [(0, 0), (0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (0, 3), (1, 3)];
        for (var pattern = 0; pattern < 256; pattern++)
        {
            var lightness = Enumerable.Repeat(1d, 8).ToArray();
            for (var bit = 0; bit < 8; bit++)
                if ((pattern & (1 << bit)) != 0) lightness[positions[bit].Y * 2 + positions[bit].X] = 0;
            Assert.Equal(0x2800 + pattern, Assert.Single(CompactDotEncoder.Encode(lightness, 2, 4, "threshold")).Value);
        }
    }

    [Theory]
    [InlineData("atkinson")]
    [InlineData("floyd")]
    [InlineData("bayer")]
    [InlineData("threshold")]
    public void DitheringIsDeterministicAndPreservesSolidEndpoints(string method)
    {
        Assert.All(CompactDotEncoder.Encode(new double[64], 8, 8, method), glyph => Assert.Equal(0x28ff, glyph.Value));
        Assert.All(CompactDotEncoder.Encode(Enumerable.Repeat(1d, 64).ToArray(), 8, 8, method), glyph => Assert.Equal(0x2800, glyph.Value));
        var gradient = Enumerable.Range(0, 256).Select(index => index / 255d).ToArray();
        Assert.Equal(CompactDotEncoder.Encode(gradient, 16, 16, method), CompactDotEncoder.Encode(gradient, 16, 16, method));
    }

    [Theory]
    [InlineData("atkinson", new int[] { 10381, 10274, 10333, 10414, 10321, 10412, 10290, 10461, 10274, 10457, 10412, 10355, 10380, 10290, 10457, 10414 })]
    [InlineData("floyd", new int[] { 10381, 10338, 10397, 10382, 10321, 10382, 10354, 10461, 10274, 10325, 10413, 10362, 10380, 10354, 10449, 10414 })]
    [InlineData("bayer", new int[] { 10381, 10289, 10397, 10413, 10261, 10380, 10291, 10453, 10289, 10389, 10381, 10295, 10380, 10293, 10397, 10413 })]
    [InlineData("threshold", new int[] { 10381, 10274, 10461, 10414, 10321, 10380, 10355, 10461, 10274, 10321, 10414, 10355, 10380, 10274, 10461, 10414 })]
    public void DithersMatchIndependentTypistReferenceFixture(string method, int[] expected)
    {
        // Golden generated by the pinned reference dither.js, not by the C# encoder.
        var lightness = Enumerable.Range(0, 128).Select(index => ((index * 37) % 127) / 126d).ToArray();
        Assert.Equal(expected, CompactDotEncoder.Encode(lightness, 16, 8, method).Select(glyph => glyph.Value));
    }

    [Fact]
    public void TransparentSourceStaysBlankInBothThemes()
    {
        var transparent = new RgbaGrid(8, 8, new byte[256]);
        foreach (var invert in new[] { false, true })
            Assert.All(CompactArtPipeline.Convert(transparent, Neutral with { Invert = invert }).Cells,
                cell => Assert.Equal(0x2800, cell.Glyph.Value));
    }

    [Fact]
    public void AutomaticLevelsExpandNarrowRangeWhileFlatInputsRemainFinite()
    {
        var narrow = Grid(8, 8, index => (byte)(100 + index));
        var output = CompactToneMapper.Apply(narrow, Neutral with { AutoLevels = true });
        Assert.True(output.Max() - output.Min() > .9);
        foreach (var look in new[] { "photo", "texture", "sketch", "soft", "poster" })
            Assert.All(CompactToneMapper.Apply(Grid(8, 8, _ => 128), new CompactArtOptions { Look = look }),
                value => Assert.True(double.IsFinite(value) && value is >= 0 and <= 1));
    }

    [Fact]
    public void NeutralSoftTonePreservesEncodedLuminanceAndGammaLightens()
    {
        var samples = Grid(72, 8, index => (byte)(30 + index % 64 * 3));
        var neutral = Neutral;
        var baseline = CompactToneMapper.Apply(samples, neutral);
        var gamma = CompactToneMapper.Apply(samples, neutral with { Gamma = 2 });
        for (var index = 0; index < baseline.Length; index++)
        {
            Assert.Equal((double)(float)((30 + index % 64 * 3) / 255d), baseline[index]);
            Assert.True(gamma[index] > baseline[index]);
        }
        Assert.Equal(baseline, CompactToneMapper.Apply(samples, neutral));
    }

    [Fact]
    public void NeutralInversionComplementsPhotoLightnessWithoutChangingGeometry()
    {
        var samples = Grid(8, 8, index => (byte)(30 + index * 3));
        var light = CompactToneMapper.Apply(samples, Neutral);
        var inverted = CompactToneMapper.Apply(samples, Neutral with { Invert = true });
        for (var index = 0; index < light.Length; index++) Assert.Equal((double)(float)(1 - light[index]), inverted[index]);
        var neutral = CompactArtPipeline.Convert(samples, Neutral with { Dither = "threshold" });
        var opposite = CompactArtPipeline.Convert(samples, Neutral with { Dither = "threshold", Invert = true });
        Assert.Equal(neutral.WidthInCells, opposite.WidthInCells);
        Assert.Equal(neutral.HeightInCells, opposite.HeightInCells);
        for (var index = 0; index < neutral.Cells.Count; index++)
            Assert.Equal(255, (neutral.Cells[index].Glyph.Value - 0x2800) ^ (opposite.Cells[index].Glyph.Value - 0x2800));
    }

    [Theory]
    [InlineData("photo")]
    [InlineData("texture")]
    [InlineData("sketch")]
    [InlineData("soft")]
    [InlineData("poster")]
    public void LooksAreBoundedAndControlsChangeStructuredFixture(string look)
    {
        var fixture = Grid(32, 32, index => (byte)(40 + ((index % 32 * 5 + index / 32 * 3 + (index % 7) * 15) % 180)));
        var options = new CompactArtOptions { Look = look, Invert = false };
        var result = CompactToneMapper.Apply(fixture, options);
        Assert.All(result, value => Assert.InRange(value, 0, 1));
        Assert.NotEqual(result, CompactToneMapper.Apply(fixture, options with { Brightness = .6 }));
        Assert.NotEqual(result, CompactToneMapper.Apply(fixture, options with { Detail = 0 }));
        Assert.NotEqual(result, CompactToneMapper.Apply(fixture, options with { Edges = 1 }));
    }

    [Fact]
    public void PipelineUsesCleanBlankAndThemeColors()
    {
        var light = CompactArtPipeline.Convert(Grid(8, 8, _ => 255), Neutral);
        Assert.Equal("⠀⠀⠀⠀\n⠀⠀⠀⠀", light.Text);
        Assert.Equal(new RgbColor(255, 255, 255), light.BackgroundColor);
        var dark = CompactArtPipeline.Convert(Grid(8, 8, _ => 0), Neutral with { Invert = true });
        Assert.Equal(light.Text, dark.Text);
        Assert.Equal(new RgbColor(0, 0, 0), dark.BackgroundColor);
        Assert.All(dark.Cells, cell => Assert.Equal(new RgbColor(255, 255, 255), cell.Color));
    }

    [Fact]
    public void InvalidShapeNonfiniteAndCancellationAreRejected()
    {
        Assert.Throws<ArgumentException>(() => CompactDotEncoder.Encode(new double[12], 3, 4, "threshold"));
        Assert.Throws<ArgumentException>(() => CompactDotEncoder.Encode(new double[8], 2, 4, "unknown"));
        Assert.Throws<ArgumentOutOfRangeException>(() => CompactDotEncoder.Encode([double.NaN, 0, 0, 0, 0, 0, 0, 0], 2, 4, "threshold"));
        Assert.Throws<ArgumentOutOfRangeException>(() => CompactDotEncoder.Encode([double.PositiveInfinity, 0, 0, 0, 0, 0, 0, 0], 2, 4, "threshold"));
        Assert.Throws<ArgumentException>(() => CompactDotEncoder.Encode([], 402, 4, "threshold"));
        Assert.Throws<ArgumentException>(() => CompactToneMapper.Apply(new RgbaGrid(8, 8, []), Neutral));
        Assert.Throws<ArgumentOutOfRangeException>(() => CompactToneMapper.Apply(Grid(8, 8, _ => 100), Neutral with { Gamma = double.PositiveInfinity }));
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        Assert.Throws<OperationCanceledException>(() => CompactToneMapper.Apply(Grid(8, 8, _ => 100), Neutral, cancellation.Token));
        Assert.Throws<OperationCanceledException>(() => CompactDotEncoder.Encode(new double[8], 2, 4, "atkinson", cancellation.Token));
    }

    private static CompactArtOptions Neutral => new() { Look = "soft", AutoLevels = false, Detail = 0, Invert = false };

    private static RgbaGrid Grid(int width, int height, Func<int, byte> sample)
    {
        var bytes = new byte[width * height * 4];
        for (var index = 0; index < width * height; index++)
        {
            bytes[index * 4] = bytes[index * 4 + 1] = bytes[index * 4 + 2] = sample(index);
            bytes[index * 4 + 3] = 255;
        }
        return new RgbaGrid(width, height, bytes);
    }
}
